//! Desktop GUI (eframe/egui).
//!
//! Layout: input files -> output settings -> run. Files can also be dropped
//! onto the window. The conversion runs on a worker thread and reports back
//! over a channel so the UI stays responsive.

use blf_decoder::convert::{
    ConvertOptions, OutputLayout, Progress, Summary, TimestampMode, convert,
};
use blf_decoder::export::OutputFormat;
use eframe::egui;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::sync::mpsc::{Receiver, channel};
use std::time::Duration;

const APP_VERSION: &str = env!("CARGO_PKG_VERSION");

pub fn run() -> eframe::Result<()> {
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_inner_size([640.0, 480.0])
            .with_min_inner_size([560.0, 420.0])
            .with_icon(window_icon()),
        ..Default::default()
    };
    eframe::run_native(
        "BLF Decoder",
        options,
        Box::new(|cc| {
            let japanese = install_cjk_font(&cc.egui_ctx);
            cc.egui_ctx.all_styles_mut(|style| {
                style.spacing.item_spacing = egui::vec2(8.0, 8.0);
                style.spacing.button_padding = egui::vec2(12.0, 6.0);
            });
            Ok(Box::new(App::new(japanese)))
        }),
    )
}

/// Window/taskbar icon, embedded as raw 64x64 RGBA generated by
/// `scripts/gen_icon.py` (the .exe file icon comes from build.rs instead).
fn window_icon() -> egui::IconData {
    egui::IconData {
        rgba: include_bytes!("../assets/icon_64.rgba").to_vec(),
        width: 64,
        height: 64,
    }
}

/// Try to load a system font with Japanese glyph coverage. egui's built-in
/// fonts have no CJK glyphs, so without this the UI falls back to English.
fn install_cjk_font(ctx: &egui::Context) -> bool {
    const CANDIDATES: &[&str] = &[
        // Windows (primary target)
        "C:\\Windows\\Fonts\\meiryo.ttc",
        "C:\\Windows\\Fonts\\YuGothM.ttc",
        "C:\\Windows\\Fonts\\msgothic.ttc",
        // macOS
        "/System/Library/Fonts/Hiragino Sans GB.ttc",
        // Linux
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf",
    ];
    for path in CANDIDATES {
        let Ok(bytes) = std::fs::read(path) else {
            continue;
        };
        let mut fonts = egui::FontDefinitions::default();
        fonts.font_data.insert(
            "cjk".to_owned(),
            Arc::new(egui::FontData::from_owned(bytes)),
        );
        for family in [egui::FontFamily::Proportional, egui::FontFamily::Monospace] {
            if let Some(list) = fonts.families.get_mut(&family) {
                list.push("cjk".to_owned());
            }
        }
        ctx.set_fonts(fonts);
        return true;
    }
    false
}

